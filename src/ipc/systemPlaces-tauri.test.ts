import { expect, test, vi } from "vitest";
import build from "../../src-tauri/build.rs?raw";
import handler from "../../src-tauri/src/lib.rs?raw";
import capability from "../../src-tauri/capabilities/default.json?raw";
import listPermission from "../../src-tauri/permissions/autogenerated/system_places_list.toml?raw";
import importPermission from "../../src-tauri/permissions/autogenerated/system_places_import.toml?raw";
import connectPermission from "../../src-tauri/permissions/autogenerated/system_mount_connect.toml?raw";
import unmountPermission from "../../src-tauri/permissions/autogenerated/system_mount_unmount.toml?raw";
import { errorKey, t } from "../i18n";
const invoke = vi.fn();
vi.mock("@tauri-apps/api/core", () => ({ invoke: (...args: unknown[]) => invoke(...args) }));
vi.mock("@tauri-apps/api/event", () => ({ listen: vi.fn() }));
import { createTauriApi } from "./tauri";

test("system commands cross IPC with exact arguments and main-window permissions", async () => {
  const api = createTauriApi();
  const cases = [
    ["system_places_list", undefined, () => api.systemPlacesList(), listPermission],
    ["system_places_import", { urls: ["smb://nas/team"] }, () => api.systemPlacesImport(["smb://nas/team"]), importPermission],
    ["system_mount_connect", { profileId: "p1" }, () => api.systemMountConnect("p1"), connectPermission],
    ["system_mount_unmount", { profileId: "p1" }, () => api.systemMountUnmount("p1"), unmountPermission],
  ] as const;
  for (const [name, args, call, permission] of cases) {
    invoke.mockResolvedValueOnce([]); await call();
    expect(invoke).toHaveBeenLastCalledWith(name, args);
    expect(build).toContain(`"${name}"`); expect(handler).toContain(`commands::${name}`);
    expect(permission).toContain(`commands.allow = ["${name}"]`);
    expect(JSON.parse(capability).permissions).toContain(`allow-${name.replaceAll("_", "-")}`);
  }
  invoke.mockRejectedValueOnce({ kind: "systemMount", message: "mount unavailable" });
  await expect(api.systemMountConnect("p1")).rejects.toMatchObject({ kind: "systemMount" });
  expect(t(errorKey("systemMount"), {}, "de")).toContain("GVfs (gio)");
  expect(t(errorKey("systemMount"), {}, "en")).toContain("KIO-FUSE");
});
